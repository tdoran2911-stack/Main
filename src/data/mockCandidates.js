function calcMatchScore(candidate) {
  let score = 0
  if (PREFERRED_SCHOOLS.includes(candidate.undergrad.school)) score += 28
  if (candidate.grad && PREFERRED_SCHOOLS.includes(candidate.grad.school)) score += 12
  if (candidate.yearsOfExperience >= 2 && candidate.yearsOfExperience <= 10) score += 20
  if (candidate.openToWork) score += 10
  // Best fit: engineers from seed–Series D software companies
  if (SEED_TO_SERIES_D.includes(candidate.currentCompany)) score += 20
  // Seniority bonus
  if (candidate.title.includes('Staff') || candidate.title.includes('Principal')) score += 5
  else if (candidate.title.includes('Senior')) score += 3
  return Math.min(100, score)
}

