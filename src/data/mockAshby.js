export function daysInStage(stageEnteredAt) {
  const diff = Date.now() - new Date(stageEnteredAt).getTime()
  const days = Math.floor(diff / 86400000)
  if (days === 0) return 'Today'
  if (days === 1) return '1 day'
  return `${days} days`
}
